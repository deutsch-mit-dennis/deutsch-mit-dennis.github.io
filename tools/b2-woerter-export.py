# Export the topic word lists (same source as the PDFs) to *-data.js for the online flashcards.
# Sources: tools/pdf/arbeitsblaetter/<slug>.py (THEMEN, KARTEN, KURZ) - edit words there only.
# Run from the repo root: py -X utf8 tools/b2-woerter-export.py   (all sets)  or  ... tools/b2-woerter-export.py dtz
import ast, json, os, sys

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# set id -> (source script slug, output file, JS variable)
SETS = {
    'b2': ('b2-wortliste-pruefungsthemen', 'b2-woerter-data.js', 'window.DM.b2Woerter'),
    'dtz': ('dtz-wortliste-themen', 'dtz-woerter-data.js', 'window.DM.woerter.dtz'),
    'a1': ('a1-wortliste-alltagsthemen', 'a1-woerter-data.js', 'window.DM.woerter.a1'),
    'b1': ('b1-wortliste-pruefungsthemen', 'b1-woerter-data.js', 'window.DM.woerter.b1'),
}
J = lambda o: json.dumps(o, ensure_ascii=False, separators=(',', ':'))
NL = '\n'


def export(sid):
    slug, out, var = SETS[sid]
    SRC = os.path.join(R, 'tools', 'pdf', 'arbeitsblaetter', slug + '.py')
    if not os.path.exists(SRC):
        print(f'skip {sid}: {SRC} missing')
        return
    src = open(SRC, encoding='utf-8').read()

    def literal(name):
        """Source text of the top-level assignment `NAME = [...]` (found with ast, nothing else of the PDF script runs)."""
        for node in ast.parse(src).body:
            if isinstance(node, ast.Assign) and any(getattr(t, 'id', None) == name for t in node.targets):
                return ast.get_source_segment(src, node)
        raise SystemExit(f'{name} not found in {SRC}')

    # N()/V() mark noun and verb in the fixed noun-verb phrases; keep them as <n>/<v> tags for the web page
    ns = {'N': lambda t: f'<n>{t}</n>', 'V': lambda t: f'<v>{t}</v>'}
    for name in ('THEMEN', 'KARTEN', 'KURZ'):
        exec(literal(name), ns)
    hard = {(ti, w) for ti, w in ns['KARTEN']}

    def front(kind, w):
        """What the front of the card shows (the PDF cards hide article / preposition the same way)."""
        if kind == 'N':
            return ' / '.join(c.split(' ', 1)[1] if ' ' in c else c for c in w.split(' / '))
        return w.split(' (')[0]

    themes = []
    for ti, (name, entries, phrases) in enumerate(ns['THEMEN']):
        words = [{'k': k, 'w': w, 'q': front(k, w), 'f': f, 'b': b, **({'h': 1} if (ti, w) in hard else {})}
                 for k, w, f, b in entries]
        words += [{'k': 'F', 'w': p, 'b': b} for p, b in phrases]
        themes.append({'name': name, 'short': ns['KURZ'][ti], 'words': words})
    n_words = sum(len(t['words']) for t in themes)
    n_hard = sum(1 for t in themes for w in t['words'] if w.get('h'))
    assert n_hard == len(hard), f'{sid}: KARTEN entry not found in THEMEN'
    head = (f'/* GENERATED by tools/b2-woerter-export.py from tools/pdf/arbeitsblaetter/{slug}.py - do not edit.\n'
            '   k: N noun · V verb · A adjective · F fixed noun-verb phrase (<n>noun</n> <v>verb</v>); w: word; q: card front;\n'
            '   f: plural / forms (may contain <b>); b: example sentence; h: 1 = also on the printable flashcards. */\n')
    theme_js = lambda t: '{"name":%s,"short":%s,"words":[%s%s]}' % (J(t['name']), J(t['short']), NL, (',' + NL).join(J(w) for w in t['words']))
    pre = 'window.DM = window.DM || {};' + NL + ('' if sid == 'b2' else 'window.DM.woerter = window.DM.woerter || {};' + NL)
    body = (pre + var + ' = {"pdf":' + J(f'material/arbeitsblaetter/{slug}.pdf') + ',"cards":' + str(n_hard)
            + ',"themes":[' + NL + (',' + NL).join(theme_js(t) for t in themes) + ']};' + NL)
    open(os.path.join(R, out), 'w', encoding='utf-8', newline='\n').write(head + body)
    print(f'{out}: {len(themes)} themes, {n_words} cards')


for sid in (sys.argv[1:] or SETS):
    export(sid)
