/* B2-Wörter nach Prüfungsthemen (#b2-woerter, #b2-woerter/<1-8>): online flashcards for the B2 word list.
   Data: b2-woerter-data.js (generated by tools/b2-woerter-export.py from the PDF source, so PDF and web stay the same).
   Loaded on demand by lazy.js (group "b2w"). Progress stays on this device:
   DM.store.b2w = { t: <theme index>, f: <filter on>, s: { "<theme>|<word>": 1 (Kann ich) | 0 (Noch üben) } } (saved with DM.save). */
(function () {
  const DM = window.DM, D = DM.b2Woerter, x = DM.esc;
  if (!D) return;
  const $ = (s, r = document) => r.querySelector(s);
  const save = () => { try { DM.save && DM.save(); } catch {} };
  const st = () => {
    const m = (DM.store.b2w ||= {});
    m.s ||= {};
    if (!(m.t >= 0 && m.t < D.themes.length)) m.t = 0;
    return m;
  };
  const keyOf = (ti, w) => `${ti}|${w.w}`;
  const KIND = {
    N: ["Nomen", "Artikel? Plural?"],
    V: ["Verb", "Präposition? Perfekt?"],
    A: ["Adjektiv", "Bedeutung? Gegenteil?"],
    F: ["Feste Verbindung", "Welches Verb passt?"],
  };
  // fixed phrases carry <n>noun</n> <v>verb</v> marks (same colours as in the PDF)
  const marks = (s, hideVerb) =>
    x(s)
      .replace(/&lt;n&gt;(.*?)&lt;\/n&gt;/g, '<b class="b2w-n">$1</b>')
      .replace(/&lt;v&gt;(.*?)&lt;\/v&gt;/g, hideVerb ? '<span class="b2w-gap" aria-label="Lücke">…</span>' : '<b class="b2w-v">$1</b>');
  const plain = (s, hideVerb) => String(s).replace(/<v>.*?<\/v>/g, hideVerb ? "…" : (m) => m).replace(/<\/?[nv]>/g, "");
  const ART = { der: "b2w-der", die: "b2w-die", das: "b2w-das" };
  const nounHtml = (w) =>
    w
      .split(" / ")
      .map((c) => {
        const [a, ...r] = c.split(" ");
        return ART[a] ? `<span class="${ART[a]}">${x(a)}</span> ${x(r.join(" "))}` : x(c);
      })
      .join(" / ");

  function render(p) {
    const S = st();
    const n = parseInt(p[1], 10);
    if (n >= 1 && n <= D.themes.length) S.t = n - 1;
    let idx = 0, flipped = false;
    const list = () => {
      const t = D.themes[S.t];
      return t.words.map((w, i) => ({ w, i })).filter(({ w }) => !S.f || S.s[keyOf(S.t, w)] !== 1);
    };
    const stats = (ti) => {
      const ws = D.themes[ti].words, k = ws.filter((w) => S.s[keyOf(ti, w)] === 1).length;
      return { k, u: ws.filter((w) => S.s[keyOf(ti, w)] === 0).length, n: ws.length };
    };
    const total = D.themes.reduce((a, t) => a + t.words.length, 0);

    DM.page(`${DM.crumbs([["Niveau B2", "#niveau/B2"], ["B2-Wörter"]])}
      <div class="dm-head"><p class="dm-kicker">Wortschatz B2 · telc Deutsch B2 und DTB B2</p><h1>B2-Wörter nach Prüfungsthemen</h1>
      <p class="dm-lead">${total} Karteikarten in ${D.themes.length} Themen. Tippe auf die Karte: Hinten stehen Artikel, Plural oder Formen und ein Beispielsatz.</p></div>
      <section class="b2w-themes" aria-labelledby="b2w-th"><h2 id="b2w-th" class="b2w-h">Thema wählen</h2>
        <div class="b2w-tgrid">${D.themes
          .map((t, i) => `<button type="button" class="b2w-tb" data-t="${i}" aria-pressed="${i === S.t}"><b>${i + 1} · ${x(t.short)}</b><small class="b2w-tb-s"></small><span class="b2w-mini" aria-hidden="true"><span></span></span></button>`)
          .join("")}</div>
      </section>
      <section class="b2w-stage" aria-labelledby="b2w-cur">
        <div class="b2w-top"><h2 id="b2w-cur" class="b2w-h"></h2>
          <label class="b2w-filter"><input type="checkbox" id="b2w-f"${S.f ? " checked" : ""}> <span>Nur Noch-üben-Wörter <small>(alles ohne „Kann ich“)</small></span></label></div>
        <p class="b2w-count" id="b2w-count" aria-live="polite"></p>
        <div id="b2w-body"></div>
      </section>
      <p class="b2w-pdf"><a href="${x(D.pdf)}" download target="_blank" rel="noopener">📄 Wortliste als PDF zum Ausdrucken</a> – mit 24 Karteikarten zum Ausschneiden.</p>`);

    const body = $("#b2w-body");
    body.innerHTML = `<button type="button" class="b2w-card" id="b2w-card" aria-describedby="b2w-hint"></button>
      <p class="b2w-hint" id="b2w-hint">Tippen, Leertaste oder Enter: Karte umdrehen · Pfeiltasten: vor und zurück</p>
      <div class="b2w-row"><button type="button" class="b2w-btn" id="b2w-say">🔊 Vorlesen</button></div>
      <div class="b2w-row b2w-rate"><button type="button" class="b2w-btn b2w-u" id="b2w-u">↻ Noch üben</button><button type="button" class="b2w-btn b2w-k" id="b2w-k">✓ Kann ich</button></div>
      <div class="b2w-row b2w-nav"><button type="button" class="b2w-btn b2w-q" id="b2w-prev">← Zurück</button><button type="button" class="b2w-btn b2w-q" id="b2w-next">Weiter →</button></div>
      <div class="b2w-end" id="b2w-end" hidden></div>`;
    const card = $("#b2w-card"), end = $("#b2w-end");

    function face(w) {
      const [kind, ask] = KIND[w.k] || ["", ""];
      if (!flipped) {
        const q = w.k === "F" ? marks(w.w, true) : x(w.q || w.w);
        return `<span class="b2w-kind">${kind}</span><span class="b2w-word">${q}</span><span class="b2w-ask">${ask}</span><span class="b2w-tap" aria-hidden="true">Tippen zum Umdrehen ↻</span>`;
      }
      const word = w.k === "F" ? marks(w.w) : w.k === "N" ? nounHtml(w.w) : x(w.w);
      return `<span class="b2w-kind">${kind} · Rückseite</span><span class="b2w-word b2w-word-b">${word}</span>${w.f ? `<span class="b2w-forms">${x(w.f)}</span>` : ""}<span class="b2w-ex">${x(w.b)}</span>`;
    }
    function draw() {
      const t = D.themes[S.t], L = list();
      $("#b2w-cur").textContent = `${S.t + 1} · ${t.name}`;
      document.querySelectorAll(".b2w-tb").forEach((b) => {
        const ti = +b.dataset.t, s = stats(ti);
        b.setAttribute("aria-pressed", String(ti === S.t));
        b.querySelector(".b2w-tb-s").textContent = `${s.k} von ${s.n} kann ich${s.u ? ` · ${s.u} üben` : ""}`;
        b.querySelector(".b2w-mini span").style.width = `${Math.round((s.k / s.n) * 100)}%`;
      });
      const s = stats(S.t);
      if (idx >= L.length) {
        card.hidden = true;
        body.querySelectorAll(".b2w-row, .b2w-hint").forEach((e) => (e.hidden = true));
        end.hidden = false;
        const nextT = (S.t + 1) % D.themes.length;
        end.innerHTML = L.length || !S.f
          ? `<p class="b2w-end-t"><b>Thema durch!</b> Du kannst ${s.k} von ${s.n} Wörtern.</p><div class="b2w-row"><button type="button" class="b2w-btn" data-again>↻ Noch einmal</button><button type="button" class="b2w-btn b2w-k" data-next>Nächstes Thema →</button></div>`
          : `<p class="b2w-end-t"><b>Super!</b> In diesem Thema ist kein Wort mehr zum Üben übrig.</p><div class="b2w-row"><button type="button" class="b2w-btn" data-all>Alle Wörter zeigen</button><button type="button" class="b2w-btn b2w-k" data-next>Nächstes Thema →</button></div>`;
        end.querySelector("[data-again]")?.addEventListener("click", () => { idx = 0; flipped = false; draw(); card.focus(); });
        end.querySelector("[data-all]")?.addEventListener("click", () => { S.f = false; $("#b2w-f").checked = false; save(); idx = 0; flipped = false; draw(); card.focus(); });
        end.querySelector("[data-next]").addEventListener("click", () => pick(nextT));
        $("#b2w-count").textContent = `${s.k} von ${s.n} kann ich`;
        return;
      }
      card.hidden = false;
      end.hidden = true;
      body.querySelectorAll(".b2w-row, .b2w-hint").forEach((e) => (e.hidden = false));
      const { w } = L[idx], mark = S.s[keyOf(S.t, w)];
      card.className = `b2w-card${flipped ? " is-back" : ""}${mark === 1 ? " is-known" : mark === 0 ? " is-practice" : ""}`;
      card.setAttribute("aria-label", `Karte ${idx + 1} von ${L.length}, ${flipped ? "Rückseite" : "Vorderseite"}. ${flipped ? plain(w.w) + ". " + (w.f ? w.f + ". " : "") + w.b : plain(w.k === "F" ? w.w : w.q || w.w, true) + ". " + (KIND[w.k] || ["", ""])[1]}`);
      card.innerHTML = face(w) + (mark === 1 ? '<span class="b2w-badge">✓ Kann ich</span>' : mark === 0 ? '<span class="b2w-badge b2w-badge-u">↻ Noch üben</span>' : "");
      $("#b2w-count").textContent = `Karte ${idx + 1} von ${L.length} · ${s.k} von ${s.n} kann ich`;
      $("#b2w-prev").disabled = idx === 0;
      $("#b2w-next").disabled = idx >= L.length - 1;
      $("#b2w-k").setAttribute("aria-pressed", String(mark === 1));
      $("#b2w-u").setAttribute("aria-pressed", String(mark === 0));
    }
    function pick(ti) {
      S.t = ti; save();
      idx = 0; flipped = false;
      draw();
      $("#b2w-cur").scrollIntoView({ block: "nearest" });
    }
    function go(d) {
      const L = list();
      const ni = Math.max(0, Math.min(L.length - 1, idx + d));
      if (ni !== idx) { idx = ni; flipped = false; draw(); }
    }
    function rate(v) {
      const L = list();
      if (!L[idx]) return;
      S.s[keyOf(S.t, L[idx].w)] = v;
      save();
      // with the filter on, a known word leaves the list and the next one slides into this place
      if (!(S.f && v === 1)) idx++;
      flipped = false;
      draw();
      if (!card.hidden) card.focus();
    }
    card.addEventListener("click", () => { flipped = !flipped; draw(); });
    $("#b2w-say").addEventListener("click", (e) => {
      const L = list(), it = L[idx];
      if (!it || !DM.speak) return;
      const w = it.w, btn = e.currentTarget;
      const text = flipped ? `${plain(w.w)}. ${w.b}` : plain(w.k === "F" ? w.w : w.q || w.w, true).replace(/…/g, "");
      btn.classList.add("is-playing");
      const ok = DM.speak(text, { onend: () => btn.classList.remove("is-playing") });
      if (ok === false) btn.classList.remove("is-playing");
    });
    $("#b2w-k").addEventListener("click", () => rate(1));
    $("#b2w-u").addEventListener("click", () => rate(0));
    $("#b2w-prev").addEventListener("click", () => go(-1));
    $("#b2w-next").addEventListener("click", () => go(1));
    $("#b2w-f").addEventListener("change", (e) => { S.f = e.target.checked; save(); idx = 0; flipped = false; draw(); });
    document.querySelectorAll(".b2w-tb").forEach((b) => b.addEventListener("click", () => pick(+b.dataset.t)));
    $(".b2w-stage").addEventListener("keydown", (e) => {
      if (e.target.closest("input")) return;
      if (e.key === "ArrowRight") { e.preventDefault(); go(1); }
      else if (e.key === "ArrowLeft") { e.preventDefault(); go(-1); }
    });
    draw();
  }

  DM.routes["b2-woerter"] = render;
})();
